#!/usr/bin/env python3
"""Export model_eval results to a cheatsheet-friendly JS bundle."""

from __future__ import annotations

import json
import sys
from datetime import UTC, datetime
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[3]
_EVAL = _REPO_ROOT / "agents" / "model_eval"
if str(_EVAL) not in sys.path:
    sys.path.insert(0, str(_EVAL))

from model_eval_core.token_stats import aggregate_suite_tokens_from_jsonl  # noqa: E402

RESULTS_DIR = _EVAL / "eval" / "results"
OUT_JS = _REPO_ROOT / "research" / "cheatsheets" / "js" / "agents-model-eval-data.js"

DIMENSIONS = [
    ("tool_use", "Tool use"),
    ("instruction_following", "Instruction following"),
    ("hallucination", "Hallucination"),
    ("sycophancy", "Sycophancy"),
    ("reasoning", "Reasoning"),
    ("math", "Math"),
    ("coding", "Coding"),
]

INFRASTRUCTURE_FAILURE_MODES = [
    ("ollama_tool_binding_unsupported", "No tool API"),
    ("missing_expected_tool", "Missing tool"),
    ("tool_required_but_not_called", "Tool not called"),
    ("malformed_tool_call_syntax", "Bad tool syntax"),
    ("agent_step_limit_stub", "Step limit"),
    ("thinking_budget_exhausted", "Think budget"),
    ("repetition_loop", "Repetition"),
    ("empty_final_answer", "Empty answer"),
]


def _load_responses(path: Path) -> list[dict]:
    rows: list[dict] = []
    if not path.exists():
        return rows
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            rows.append(
                {
                    "case_id": row.get("case_id"),
                    "dimension": row.get("dimension"),
                    "prompt": row.get("prompt", ""),
                    "final_answer": row.get("final_answer", ""),
                    "passed": bool(row.get("passed")),
                    "failure_modes": row.get("failure_modes") or [],
                    "signals": row.get("signals") or {},
                    "latency_s": row.get("latency_s"),
                    "runtime": row.get("runtime"),
                    "gpu": row.get("gpu"),
                }
            )
    return rows


def build_payload() -> dict:
    """Aggregate all model result folders that contain summary.json."""
    models: list[dict] = []
    for model_dir in sorted(RESULTS_DIR.iterdir()):
        if not model_dir.is_dir():
            continue
        summary_path = model_dir / "summary.json"
        if not summary_path.exists():
            continue
        summary = json.loads(summary_path.read_text(encoding="utf-8"))
        jsonl_path = model_dir / "responses.jsonl"
        cases = _load_responses(jsonl_path)
        wall_s = (summary.get("runtime") or {}).get("wall_s")
        token_stats = summary.get("token_stats") or aggregate_suite_tokens_from_jsonl(
            jsonl_path,
            wall_s=wall_s,
        )
        models.append(
            {
                "id": summary.get("model_dir", model_dir.name),
                "name": summary.get("model_name", model_dir.name),
                "params": summary.get("params"),
                "ollama_tag": summary.get("ollama_tag"),
                "quantization": summary.get("quantization"),
                "total_passed": summary.get("total_passed", 0),
                "total_cases": summary.get("total_cases", 0),
                "tool_use_capable": summary.get("tool_use_capable", True),
                "runtime": summary.get("runtime") or {},
                "gpu_vram_mib": summary.get("gpu_vram_mib") or {},
                "metrics_backfill": summary.get("metrics_backfill") or {},
                "by_dimension": summary.get("by_dimension") or {},
                "infrastructure_failure_counts": summary.get("infrastructure_failure_counts") or {},
                "token_stats": token_stats,
                "cases": cases,
            }
        )
    return {
        "generated_at": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "suite_note": "ReAct harness, 44 curated cases (7 dimensions); pass = probe heuristics.",
        "dimensions": [{"id": d, "label": label} for d, label in DIMENSIONS],
        "infrastructure_failure_modes": [
            {"id": mode_id, "label": label} for mode_id, label in INFRASTRUCTURE_FAILURE_MODES
        ],
        "models": models,
    }


def main() -> None:
    """Write agents-model-eval-data.js for static cheatsheet pages."""
    payload = build_payload()
    OUT_JS.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(payload, ensure_ascii=False, indent=2)
    OUT_JS.write_text(
        "/** Generated by agents/model_eval/scripts/export_cheatsheet_data.py — do not edit. */\n"
        f"window.AGENTS_MODEL_EVAL_DATA = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT_JS} ({len(payload['models'])} models)")


if __name__ == "__main__":
    main()
